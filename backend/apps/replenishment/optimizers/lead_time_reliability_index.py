class LeadTimeReliabilityIndexOptimizer:
    """Execution engine for Historical Lead Time Reliability & P95 SLA Index."""
    def __init__(self, param_id: str):
        self.param = OPTIMIZER_PARAM_LEAD_TIME_RELIABILITY_INDEX_REGISTRY.get(param_id)

    def calculate_recommendation(self, current_stock: float, on_order: float = 0.0) -> Dict[str, Any]:
        if not self.param:
            return {"suggested_quantity": 0, "urgency": "OPTIMAL"}
        net_stock = current_stock + on_order
        if net_stock <= self.param.reorder_point:
            raw_order = max(0.0, self.param.target_max_stock - net_stock)
            rounded = math.ceil(raw_order / self.param.case_multiple) * self.param.case_multiple
            final_qty = max(rounded, self.param.moq_units)
            urgency = "CRITICAL" if net_stock < (self.param.safety_stock) else "WARNING"
            return {"suggested_quantity": final_qty, "urgency": urgency, "rop": self.param.reorder_point, "ss": self.param.safety_stock}
        return {"suggested_quantity": 0, "urgency": "OPTIMAL", "rop": self.param.reorder_point, "ss": self.param.safety_stock}
